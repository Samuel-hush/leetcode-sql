-- ================================================
-- 题目：LC182 查找重复的电子邮箱
-- 考点：GROUP BY + HAVING
-- ================================================
-- 要求：找出出现次数大于 1 的 email
-- 涉及表：Person（id, email）
-- 套路：
--   · 找重复：GROUP BY 列 HAVING COUNT(*) > 1
-- ================================================

SELECT email FROM Person GROUP BY email HAVING COUNT(*) > 1;
