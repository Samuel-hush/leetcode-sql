-- ================================================
-- 题目：LC180 连续出现的数字
-- 考点：自连接错位
-- ================================================
-- 要求：找出连续出现至少 3 次的数字
-- 涉及表：Logs（id, num）
-- 套路：
--   · 连续 N 次 = 表连自己 N 次，错位 id = id-1，再要求值相等
-- ================================================

SELECT DISTINCT l1.num AS ConsecutiveNums
FROM Logs l1, Logs l2, Logs l3
WHERE l1.id = l2.id - 1 AND l2.id = l3.id - 1
  AND l1.num = l2.num AND l2.num = l3.num;
