-- ================================================
-- 题目：LC196 删除重复的电子邮箱
-- 考点：DELETE 自连接
-- ================================================
-- 要求：删除重复 email，保留 id 最小的
-- 涉及表：Person（id, email）
-- 套路：
--   · 删重复留最小：DELETE 大表 FROM 大表 JOIN 小表 ON 重复键 AND 大表.id > 小表.id
-- ================================================

DELETE p1
FROM Person p1 JOIN Person p2
  ON p1.email = p2.email AND p1.id > p2.id;
