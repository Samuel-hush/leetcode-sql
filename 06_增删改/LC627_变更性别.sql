-- ================================================
-- 题目：LC627 变更性别
-- 考点：UPDATE + IF/CASE
-- ================================================
-- 要求：把 sex 的 m 变 f、f 变 m
-- 涉及表：Salary（id, name, sex, salary）
-- 套路：
--   · UPDATE ... SET 列 = IF/CASE(...) 按条件改值，无 WHERE
-- ================================================

UPDATE Salary SET sex = IF(sex = 'm', 'f', 'm');
