-- ================================================
-- 题目：LC595 大的国家
-- 考点：WHERE OR
-- ================================================
-- 要求：面积 >300 万或人口 >2500 万的国家
-- 涉及表：World（name, area, population, gdp）
-- 套路：
--   · 简单 OR 条件
-- ================================================

SELECT name, population, area FROM World
WHERE area > 3000000 OR population > 25000000;
